// Generates the one script the user runs with sudo, plus the cleanup script. This tool never runs sudo and never
// writes under /Library: it only writes these files into the stage dir and prints the commands.
//
// Handshake (stage dir is owned by the user, mode 0700):
//   root script: install variant V -> write ready-V -> wait for done-V -> next variant; EXIT trap removes the folder.
//   probe tool:  wait for ready-V -> run phase V as the user -> write done-V.
import { chmodSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { MANAGED_DIR, MARKER, VARIANTS } from "./fixtures.ts";

const q = (s: string): string => `'${s.replaceAll("'", `'\\''`)}'`;

const GUARD = `[ "$(id -u)" = 0 ] || { echo "run with sudo"; exit 1; }`;
const NOT_OURS = `if [ -e "$DST" ] && [ ! -f "$DST/${MARKER}" ]; then echo "$DST exists and is not ours; refusing"; exit 1; fi`;

export const installScript = (stage: string): string =>
  `#!/bin/bash
# Generated by release:probe:managed. Installs each variant as root, waits for the probe tool, removes the folder at the end.
# Root never writes into $STAGE (it is user-owned): it only reads from it and tests for the tool's done/abort files.
set -euo pipefail
STAGE=${q(stage)}
DST=${q(MANAGED_DIR)}
WAIT_SECS=900
${GUARD}
${NOT_OURS}
if [ -n "$(find "$STAGE/ClaudeCode" "$STAGE/variants" -type l 2>/dev/null)" ]; then echo "symlink in $STAGE; refusing"; exit 1; fi
cleanup() { if [ -f "$DST/${MARKER}" ]; then rm -rf "$DST"; echo "removed $DST"; fi; }
trap cleanup EXIT
for V in ${VARIANTS.join(" ")}; do
  ${NOT_OURS}
  rm -rf "$DST"
  mkdir -p "$(dirname "$DST")"
  cp -RP "$STAGE/ClaudeCode" "$DST"
  rm -f "$DST/managed-settings.json"
  cp -P "$STAGE/variants/$V/managed-settings.json" "$DST/managed-settings.json"
  chown -R root:wheel "$DST"
  chmod -R go-w "$DST"
  echo "installed variant $V"
  # readiness signal for the tool: root-owned file inside the managed folder
  printf '%s' "$V" > "$DST/.variant"
  chmod 644 "$DST/.variant"
  waited=0
  until [ -f "$STAGE/done-$V" ]; do
    if [ -e "$STAGE/abort" ]; then echo "abort requested"; exit 1; fi
    if [ "$waited" -ge "$WAIT_SECS" ]; then echo "timed out waiting for the probe tool"; exit 1; fi
    sleep 1; waited=$((waited + 1))
  done
done
echo "all variants done"
`;

export const cleanupScript = (): string =>
  `#!/bin/bash
# Generated by release:probe:managed. Removes ${MANAGED_DIR} only when it carries our marker file.
set -euo pipefail
DST=${q(MANAGED_DIR)}
${GUARD}
[ -e "$DST" ] || { echo "nothing to remove"; exit 0; }
[ -f "$DST/${MARKER}" ] || { echo "$DST is not ours; refusing"; exit 1; }
rm -rf "$DST"; echo removed
`;

export type Scripts = { install: string; cleanup: string };

export const writeScripts = (stage: string): Scripts => {
  const install = join(stage, "install.sh");
  const cleanup = join(stage, "cleanup.sh");
  writeFileSync(install, installScript(stage));
  writeFileSync(cleanup, cleanupScript());
  chmodSync(install, 0o700);
  chmodSync(cleanup, 0o700);
  return { install, cleanup };
};

/** The command lines shown to the user. Paths are quoted. */
export const installCommand = (s: Scripts): string =>
  `sudo /bin/bash ${q(s.install)}`;
export const cleanupCommand = (s: Scripts): string =>
  `sudo /bin/bash ${q(s.cleanup)}`;
